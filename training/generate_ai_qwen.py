def main(target=300):
    print(f"loading {MODEL} ...", flush=True)
    tok = AutoTokenizer.from_pretrained(MODEL)
    if tok.pad_token_id is None:
        tok.pad_token_id = tok.eos_token_id
    model = AutoModelForCausalLM.from_pretrained(
        MODEL, dtype=torch.float32, low_cpu_mem_usage=True,
    ).eval()

    samples = []
    per_prompt = max(1, target // len(PROMPTS))
    for i, prompt in enumerate(PROMPTS):
        msgs = [{"role": "user", "content": prompt}]
        fmt = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
        inputs = tok([fmt], return_tensors="pt")
        input_len = inputs["input_ids"].shape[-1]
        for j in range(per_prompt):
            torch.manual_seed(i * 100 + j)
            with torch.no_grad():
                out = model.generate(
                    **inputs, do_sample=True, temperature=0.9, top_p=0.95,
                    max_new_tokens=180, pad_token_id=tok.eos_token_id,
                )
            text = tok.decode(out[0, input_len:], skip_special_tokens=True)
            if 200 < len(text) < 3000:
                samples.append(text.strip())
        print(f"  prompt {i+1}/{len(PROMPTS)}: total={len(samples)}", flush=True)

    with OUT.open("w", encoding="utf-8") as f:
        for t in samples:
            f.write(json.dumps({"text": t, "label": 1}, ensure_ascii=False) + "\n")
    print(f"wrote {OUT}: {len(samples)} samples")


if __name__ == "__main__":
    main()